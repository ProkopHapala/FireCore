def set_atom_params():
    eff.setAtomParams(ATOMPARAMS2, mode=1)


def groups(na, ne):
    """DOF block slices: atom pos | electron pos | electron size."""
    return {'apos': slice(0, na*3), 'epos': slice(na*3, (na+ne)*3), 'esize': slice((na+ne)*3, (na+ne)*3+ne)}


def parse_fixmask_e(xyz, na, ne):
    """Parse '.'-prefix fixed flags from an eFF xyz (na atoms then ne electrons). Returns bool[nDOFs]."""
    fix = np.zeros(na*3+ne*3+ne, dtype=bool)
    with open(xyz) as f:
        lines = f.read().splitlines()
    rows = [l for l in lines[2:2+na+ne]]
    for i, l in enumerate(rows):
        name = l.split()[0]
        fixed = name.startswith('.')
        if not fixed: continue
        if i < na:
            fix[i*3:i*3+3] = True
        else:
            ie = i - na
            fix[na*3+ie*3:na*3+ie*3+3] = True
            fix[(na+ne)*3+ie] = True
    return fix


def load_e(xyz, verbosity=0):
    """processXYZ_e path: explicit electrons. Returns (na, ne, fixed_mask)."""
    eff.setVerbosity(verbosity)
    eff.bVel = True                       # so getBuffs() fetches vDOFs/invMasses
    eff.processXYZ_e(xyz, nstepMax=0, xyz_out=None, fgo_out=None)
    eff.getBuffs()
    return eff.na, eff.ne, parse_fixmask_e(xyz, eff.na, eff.ne)


def load_a(xyz, verbosity=0, bCoreElectrons=True, bPaired=False, coreMode=b'a'):
    """processXYZ path: atom-only xyz, electrons generated by builder, atoms hard-fixed.

    NOTE: processXYZ only sets up its fixed_inds constrain block when nstepMax>0;
    with nstepMax=0 (our builder-only call) ff.nfix stays 0, so we apply the same
    constraints explicitly via set_constrains - otherwise stock run() leaves atoms free."""
    eff.setVerbosity(verbosity)
    eff.bVel = True
    eff.processXYZ(xyz, nstepMax=0, bCoreElectrons=bCoreElectrons, bChangeCore=False, bChangeEsize=True,
                   bPaired=bPaired, coreMode=coreMode, xyz_out=None, fgo_out=None)
    eff.getBuffs()
    nfix = eff.na
    fixed_poss = np.zeros((nfix, 4), dtype=np.float64)
    fixed_poss[:, :3] = eff.apos.reshape(nfix, 3)
    fixed_inds = np.tile(np.array([0, 7], dtype=np.int32), (nfix, 1))
    fixed_inds[:, 0] = np.arange(nfix, dtype=np.int32)
    eff.set_constrains(nfix, fixed_poss, fixed_inds, bRealloc=True)
    fixed = np.zeros(eff.nDOFs, dtype=bool)
    fixed[:eff.na*3] = True          # processXYZ hard-fixes all nuclei via fixed_inds
    return eff.na, eff.ne, fixed


def snapshot():
    return eff.pDOFs.copy()

def restore(p0):
    eff.pDOFs[:] = p0
    eff.vDOFs[:] = 0.0


def hessian(h=1e-4, fixed=None):
    """Numerical Hessian H_ij = -df_i/dx_j via central differences (free DOFs only)."""
    n = eff.nDOFs
    free = ~fixed if fixed is not None else np.ones(n, bool)
    idx = np.nonzero(free)[0]
    H = np.zeros((n, n))
    for j in idx:
        x0 = eff.pDOFs[j]
        eff.pDOFs[j] = x0+h; eff.eval(); fp = eff.fDOFs.copy()
        eff.pDOFs[j] = x0-h; eff.eval(); fm = eff.fDOFs.copy()
        eff.pDOFs[j] = x0
        H[:, j] = -(fp - fm)/(2*h)
    eff.eval()
    return 0.5*(H + H.T)


def prec_masses(na, ne, fixed, k_target=30.0):
    """invM_i = k_ref/(|k_ii|+k_ref) in (0,1]: soft DOFs keep ~unit mass,
    stiff DOFs get heavy mass so omega^2 = k*invM saturates at ~k_ref.
    |k_ii| (not k_ii) because esize DOFs often sit on concave-down slopes (k<0)
    which are still steep directions needing heavy mass, not ultralight ones."""
    kd = np.abs(hessian_diag(fixed=fixed))
    invM = k_target/(kd + k_target)
    if fixed is not None:
        invM[fixed] = 0.0
    return invM, kd


def phys_masses(na, ne):
    """Physical masses via C++ makeMasses (bMass=True) read from invMasses buffer."""
    eff.initOpt(dt=0.001, damping=0.1, f_limit=100.0, bMass=True)
    return eff.invMasses.copy()


def hessian_diag(h=1e-4, fixed=None):
    """Only diagonal k_ii = -df_i/dx_i (2 evals per free DOF)."""
    n = eff.nDOFs
    free = ~fixed if fixed is not None else np.ones(n, bool)
    d = np.zeros(n)
    for j in np.nonzero(free)[0]:
        x0 = eff.pDOFs[j]
        eff.pDOFs[j] = x0+h; eff.eval(); fp = eff.fDOFs[j]
        eff.pDOFs[j] = x0-h; eff.eval(); fm = eff.fDOFs[j]
        eff.pDOFs[j] = x0
        d[j] = -(fp - fm)/(2*h)
    eff.eval()
    return d


def damp_func(c, damping, cvf_min, cvf_max):
    """DynamicOpt::damp_func (smooth variant)."""
    if c < cvf_min:   return 0.0, 0.0
    if c > cvf_max:   return 1.0-damping, damping
    f = (c - cvf_min)/(cvf_max - cvf_min)
    return (1.0-damping)*f, damping*f


def newton(nstep, fixed=None, Fconv=1e-6, k_floor=1.0, trust=1.0, dr_limit=0.2,
           recompute=0, beta=0.0, rec_every=1):
    """Diagonal-Newton descent: dx_i = trust * f_i/max(|k_ii|,k_floor), |dx|<dr_limit.
    k_ii from FD Hessian diagonal; recompute>0 refreshes it every N steps (costs 2*nfree evals).
    beta>0 adds heavy-ball momentum on the preconditioned step.
    Returns trace dict like fire() plus 'n_evals' (true cost incl. Hessian FD evals)."""
    p, v, f = eff.pDOFs, eff.vDOFs, eff.fDOFs
    n = len(p)
    free = ~fixed if fixed is not None else np.ones(n, dtype=bool)
    g = groups(eff.na, eff.ne)
    kd = None; n_evals = 0
    F2conv = Fconv*Fconv
    v[:] = 0.0
    rec = {k: [] for k in ['E', 'Fu', 'Fpos_e', 'Fsize', 'Fpos_a', 'n_evals']}
    itr = 0
    for itr in range(nstep):
        E = eff.eval(); n_evals += 1
        if fixed is not None:
            f[fixed] = 0.0
        if kd is None or (recompute and itr % recompute == 0):
            kd = np.abs(hessian_diag(fixed=fixed)) + k_floor   # 2*nfree evals inside
            n_evals += 2*int(free.sum()); E = eff.eval(); n_evals += 1
            if fixed is not None:
                f[fixed] = 0.0
        step = f/np.maximum(kd, k_floor)*trust
        np.clip(step, -dr_limit, dr_limit, out=step)
        if fixed is not None:
            step[fixed] = 0.0
        if beta > 0.0:
            v[free] = v[free]*beta + step[free]*(1-beta)
            step = v
        p[free] += step[free]
        esz = p[g['esize']]
        np.clip(esz, 1e-3, None, out=esz)
        if itr % rec_every == 0:
            ff = float((f[free]**2).sum())
            rec['E'].append(E); rec['Fu'].append(np.sqrt(ff))
            rec['Fpos_e'].append(np.sqrt((f[g['epos']]**2).sum())); rec['Fsize'].append(np.sqrt((f[g['esize']]**2).sum()))
            rec['Fpos_a'].append(np.sqrt((f[g['apos']]**2).sum())); rec['n_evals'].append(n_evals)
        if float((f[free]**2).sum()) < F2conv:
            break
    out = {k: np.array(x) for k, x in rec.items()}
    out['iters'] = itr+1
    out['n_evals_tot'] = n_evals
    out['converged'] = bool(float((f[free]**2).sum()) < F2conv)
    out['E_final'] = E
    return out


def fire(nstep, dt=0.001, damping=0.1, invM=None, f_limit=100.0,
         finc=1.1, fdec=0.5, falpha=0.8, minLastNeg=3, dtmin_frac=0.1, cv_kill=0.0,
         cvf_min=-0.1, cvf_max=0.1, smooth=False,
         fixed=None, Fconv=1e-3, na=None, ne=None, rec_every=1,
         kd_refresh=0, k_ref=None):
    """
    Exact replica of run(ialg=2) = loop{ eval(); move_FIRE(); clamp esize; }.
    Returns dict of per-iteration traces; iters = number of steps actually run.
    invM: per-DOF inverse masses (default all-1, matching bMass=false).
    """
    na_, ne_ = (eff.na, eff.ne) if (na is None or ne is None) else (na, ne)
    g = groups(na_, ne_)
    p, v, f = eff.pDOFs, eff.vDOFs, eff.fDOFs
    n = len(p)
    if invM is None: invM = np.ones(n)
    invM = invM.copy()
    free = ~fixed if fixed is not None else np.ones(n, dtype=bool)
    dt_max, dt_min, damp_max = dt, dt*dtmin_frac, damping
    v[:] = 0.0
    lastNeg = 0
    F2conv = Fconv*Fconv
    rec = {k: [] for k in ['E', 'Fm', 'Fu', 'Fpos_e', 'Fsize', 'Fpos_a', 'cos', 'dt', 'damp', 'Vsize', 'Vpos_e']}
    itr = 0
    for itr in range(nstep):
        E = eff.eval()
        if fixed is not None:
            f[fixed] = 0.0; v[fixed] = 0.0       # clear_fixed_dynamics equivalent
        fm = f*invM                               # mass-weighted force (DynamicOpt::project_vf)
        ff = (fm[free]**2).sum(); vv = (v[free]**2).sum(); vf = (v[free]*fm[free]).sum()
        f_len = np.sqrt(ff); v_len = np.sqrt(vv)
        cos_vf = vf/(f_len*v_len + FF_SAFETY)
        renorm = v_len/(f_len + FF_SAFETY)
        # ---- velocity mixing
        if smooth:
            cv, cfb = damp_func(cos_vf, damping, cvf_min, cvf_max)
            cf = renorm*cfb
        else:
            if cos_vf < 0.0: cv, cf = cv_kill, 0.0
            else:            cv, cf = 1.0-damping, renorm*damping
        v[free] = v[free]*cv + fm[free]*cf
        # ---- FIRE dt/damping update
        if cos_vf < 0.0:
            dt = max(dt*fdec, dt_min); lastNeg = 0; damping = damp_max
        else:
            if lastNeg > minLastNeg:
                dt = min(dt*finc, dt_max); damping *= falpha
            lastNeg += 1
        # ---- LeapFrog with f_limit cap
        dt_ = dt
        if ff > f_limit*f_limit:
            dt_ *= np.sqrt(f_limit/np.sqrt(ff))
        v[free] += fm[free]*dt_
        p[free] += v[free]*dt_
        # ---- esize clamp (matches run() esize>=1e-3)
        esz = p[g['esize']]
        np.clip(esz, 1e-3, None, out=esz)
        if kd_refresh and (itr+1) % kd_refresh == 0:
            kdn = np.abs(hessian_diag(fixed=fixed))
            invM[free] = k_ref/(kdn[free]+k_ref)
            eff.eval()                              # restore forces consistent with current state
        if itr % rec_every == 0:
            rec['E'].append(E);        rec['Fm'].append(f_len);   rec['Fu'].append(np.sqrt((f[free]**2).sum()))
            rec['Fpos_e'].append(np.sqrt((f[g['epos']]**2).sum())); rec['Fsize'].append(np.sqrt((f[g['esize']]**2).sum()))
            rec['Fpos_a'].append(np.sqrt((f[g['apos']]**2).sum()))
            rec['Vsize'].append(np.sqrt((v[g['esize']]**2).sum())); rec['Vpos_e'].append(np.sqrt((v[g['epos']]**2).sum()))
            rec['cos'].append(cos_vf); rec['dt'].append(dt);      rec['damp'].append(damping)
        if ff < F2conv:
            break
    out = {k: np.array(x) for k, x in rec.items()}
    out['iters'] = itr+1
    out['converged'] = bool(ff < F2conv)
    out['E_final'] = E
    return out


def fire_groups(nstep, dt=0.001, damping=0.1, invM=None, f_limit=100.0,
                finc=1.1, fdec=0.5, falpha=0.8, minLastNeg=3, dtmin_frac=0.1,
                fixed=None, Fconv=1e-3, group_mode='type', na=None, ne=None):
    """Per-group FIRE: each DOF group has its own cos_vf/dt/damping/lastNeg, so a
    ringing stiff group no longer pins the whole system at dt_min.
    group_mode: 'type' = {apos, epos, esize}; 'particle' = per-atom + per-electron
    (each electron = its 3 epos + 1 esize DOFs together)."""
    na_, ne_ = (eff.na, eff.ne) if (na is None or ne is None) else (na, ne)
    g = groups(na_, ne_)
    p, v, f = eff.pDOFs, eff.vDOFs, eff.fDOFs
    n = len(p)
    if invM is None: invM = np.ones(n)
    invM = invM.copy()
    free = ~fixed if fixed is not None else np.ones(n, dtype=bool)
    if group_mode == 'type':
        grp = [g['apos'], g['epos'], g['esize']]
    elif group_mode == 'particle':
        grp = [slice(ia*3, ia*3+3) for ia in range(na_)]
        grp += [np.r_[na_*3+ie*3:na_*3+ie*3+3, (na_+ne_)*3+ie] for ie in range(ne_)]
    ng = len(grp)
    dt_g = np.full(ng, dt); dt_min = dt*dtmin_frac; dt_max = dt
    damp_g = np.full(ng, damping); damp_max = damping
    lastNeg = np.zeros(ng, dtype=int)
    v[:] = 0.0
    F2conv = Fconv*Fconv
    rec = {k: [] for k in ['E', 'Fu', 'dt', 'cos']}
    itr = 0
    for itr in range(nstep):
        E = eff.eval()
        if fixed is not None:
            f[fixed] = 0.0; v[fixed] = 0.0
        fm = f*invM
        ff = (fm[free]**2).sum()
        cos0 = 0.0
        for j, sl in enumerate(grp):
            idx = np.arange(n)[sl] if not isinstance(sl, slice) else np.arange(n)[sl]
            m = free[idx]
            if not m.any(): continue
            fmG = fm[idx][m]; vG = v[idx][m]
            ffg = (fmG**2).sum(); vvg = (vG**2).sum(); vfg = (vG*fmG).sum()
            f_len = np.sqrt(ffg); v_len = np.sqrt(vvg)
            cos_vf = vfg/(f_len*v_len + FF_SAFETY); cos0 = cos_vf
            renorm = v_len/(f_len + FF_SAFETY)
            if cos_vf < 0.0: cv, cf = 0.0, 0.0
            else:            cv, cf = 1.0-damp_g[j], renorm*damp_g[j]
            v[idx[m]] = vG*cv + fmG*cf
            if cos_vf < 0.0:
                dt_g[j] = max(dt_g[j]*fdec, dt_min); lastNeg[j] = 0; damp_g[j] = damp_max
            else:
                if lastNeg[j] > minLastNeg:
                    dt_g[j] = min(dt_g[j]*finc, dt_max); damp_g[j] *= falpha
                lastNeg[j] += 1
            dt_ = dt_g[j]
            if ff > f_limit*f_limit:
                dt_ *= np.sqrt(f_limit/np.sqrt(ff))
            v[idx[m]] += fmG*dt_
            p[idx[m]] += v[idx[m]]*dt_
        esz = p[g['esize']]
        np.clip(esz, 1e-3, None, out=esz)
        if itr % 1 == 0:
            rec['E'].append(E); rec['Fu'].append(np.sqrt((f[free]**2).sum()))
            rec['dt'].append(dt_g.copy()); rec['cos'].append(cos0)
        if ff < F2conv:
            break
    out = {k: np.array(x) for k, x in rec.items()}
    out['iters'] = itr+1
    out['converged'] = bool(ff < F2conv)
    out['E_final'] = E
    return out


def fire_secant(nstep, dt=0.001, damping=0.1, invM=None, f_limit=100.0,
                finc=1.1, fdec=0.5, falpha=0.8, minLastNeg=3, dtmin_frac=0.1,
                fixed=None, Fconv=1e-3, k_ref=30.0, ema=0.9, kmin=1e-2, kmax=1e7,
                dx_min=1e-6, rec_every=1):
    """FIRE with online secant-diagonal mass adaptation — zero extra force evals.
    Per step: k_i ≈ -df_i/dx_i from (f_i - f_prev_i)/(x_i - x_prev_i), EMA-smoothed,
    clamped to [kmin,kmax], invM_i = k_ref/(k_i + k_ref) ∈ (0,1]."""
    g = groups(eff.na, eff.ne)
    p, v, f = eff.pDOFs, eff.vDOFs, eff.fDOFs
    n = len(p)
    if invM is None: invM = np.ones(n)
    invM = invM.copy()
    free = ~fixed if fixed is not None else np.ones(n, dtype=bool)
    dt_max, dt_min, damp_max = dt, dt*dtmin_frac, damping
    v[:] = 0.0
    lastNeg = 0
    F2conv = Fconv*Fconv
    kd = np.ones(n)*k_ref          # start ~neutral (invM~0.5) — or k_ref for invM=0.5
    invM[free] = k_ref/(kd[free]+k_ref)
    p_prev = p.copy(); f_prev = f.copy()
    rec = {k: [] for k in ['E', 'Fu', 'cos', 'dt']}
    itr = 0
    for itr in range(nstep):
        E = eff.eval()
        if fixed is not None:
            f[fixed] = 0.0; v[fixed] = 0.0
        # ---- online secant curvature estimate
        dx = p - p_prev; df = f - f_prev
        m = (np.abs(dx) > dx_min) & free
        kn = -df[m]/dx[m]
        kn = np.clip(np.abs(kn), kmin, kmax)
        kd[m] = ema*kd[m] + (1-ema)*kn
        invM[free] = k_ref/(kd[free]+k_ref)
        p_prev[:] = p; f_prev[:] = f
        # ---- standard FIRE update
        fm = f*invM
        ff = (fm[free]**2).sum(); vv = (v[free]**2).sum(); vf = (v[free]*fm[free]).sum()
        f_len = np.sqrt(ff); v_len = np.sqrt(vv)
        cos_vf = vf/(f_len*v_len + FF_SAFETY)
        renorm = v_len/(f_len + FF_SAFETY)
        if cos_vf < 0.0: cv, cf = 0.0, 0.0
        else:            cv, cf = 1.0-damping, renorm*damping
        v[free] = v[free]*cv + fm[free]*cf
        if cos_vf < 0.0:
            dt = max(dt*fdec, dt_min); lastNeg = 0; damping = damp_max
        else:
            if lastNeg > minLastNeg:
                dt = min(dt*finc, dt_max); damping *= falpha
            lastNeg += 1
        dt_ = dt
        if ff > f_limit*f_limit:
            dt_ *= np.sqrt(f_limit/np.sqrt(ff))
        v[free] += fm[free]*dt_
        p[free] += v[free]*dt_
        esz = p[g['esize']]
        np.clip(esz, 1e-3, None, out=esz)
        if itr % rec_every == 0:
            rec['E'].append(E); rec['Fu'].append(np.sqrt((f[free]**2).sum()))
            rec['cos'].append(cos_vf); rec['dt'].append(dt)
        if ff < F2conv:
            break
    out = {k: np.array(x) for k, x in rec.items()}
    out['iters'] = itr+1
    out['converged'] = bool(ff < F2conv)
    out['E_final'] = E
    return out


def bfgs(nstep, fixed=None, Fconv=1e-3, dr_limit=0.2, tr0=0.05, tr_max=1.0,
         tr_grow=1.2, tr_shrink=0.5, sy_min=1e-12, h0=1.0, rec_every=1):
    """Trust-region dense BFGS — no line search, monotone in E.
    Step d = H_inv f clipped to trust radius tr (and per-DOF dr_limit).
    Accept iff E_new <= E_cur; reject => revert x (eval already done, no extra cost).
    BFGS update only on accepted steps with s.y > sy_min (skips nonsmooth kinks).
    H_inv init = h0*I (first steps ~small GD scaled by trust)."""
    g = groups(eff.na, eff.ne)
    p, v, f = eff.pDOFs, eff.vDOFs, eff.fDOFs
    n = len(p)
    free = ~fixed if fixed is not None else np.ones(n, dtype=bool)
    idx = np.nonzero(free)[0]
    m = len(idx)
    Hi = np.eye(m)*h0
    tr = tr0
    E = eff.eval(); f_cur = f.copy(); x_cur = p.copy(); E_cur = E
    rec = {k: [] for k in ['E', 'Fu', 'tr', 'rej']}
    itr = 0; n_rej = 0
    for itr in range(nstep):
        d = Hi @ f_cur[idx]
        if d @ f_cur[idx] <= 0.0:            # safeguard: H_inv went indefinite -> reset to GD
            Hi = np.eye(m)*h0; d = Hi @ f_cur[idx]
        dn = np.linalg.norm(d)
        if dn > tr: d *= tr/dn
        np.clip(d, -dr_limit, dr_limit, out=d)
        p[idx] += d
        esz = p[g['esize']]
        np.clip(esz, 1e-3, None, out=esz)
        E_new = eff.eval(); f_new = f.copy()
        if E_new <= E_cur:                       # accept
            s = p[idx] - x_cur[idx]; y = f_cur[idx] - f_new[idx]   # y = H s (force form)
            sy = s @ y
            if sy > sy_min:
                rho = 1.0/sy
                Hy = Hi @ y
                A = np.outer(s, s)*(sy + y @ Hy)*rho*rho
                Hi += A - (np.outer(Hy, s) + np.outer(s, Hy))*rho
            x_cur[:] = p; f_cur[:] = f_new; E_cur = E_new
            tr = min(tr*tr_grow, tr_max); rej = 0
        else:                                    # reject — revert
            p[idx] = x_cur[idx]; eff.eval(); f_cur = f.copy()
            tr *= tr_shrink; rej = 1; n_rej += 1
        Fu = np.sqrt((f_cur[idx]**2).sum())
        if itr % rec_every == 0:
            rec['E'].append(E_cur); rec['Fu'].append(Fu)
            rec['tr'].append(tr); rec['rej'].append(rej)
        if Fu < Fconv:
            break
    out = {k: np.array(x) for k, x in rec.items()}
    out['iters'] = itr+1; out['converged'] = bool(Fu < Fconv)
    out['E_final'] = E_cur; out['n_rej'] = n_rej
    return out


def run_cpp(nstep, dt, Fconv=1e-3, ialg=2, damping=0.1, f_limit=100.0, bMass=False, invM=None):
    """C++ reference path: initOpt + run() with outE/outF trace."""
    eff.initOpt(dt=dt, damping=damping, f_limit=f_limit, bMass=bMass)
    if invM is not None:
        eff.invMasses[:] = invM          # overwrite masses after initOpt/makeMasses
    outE = np.full(nstep, np.nan); outF = np.full(nstep, np.nan)
    eff.run(nstep, dt, Fconv, ialg, outE=outE, outF=outF)
    n = int(np.isfinite(outE).sum())
    return outE[:n], outF[:n]


def summarize(tr, tag='', fconv_marks=(1e-3, 1e-4, 1e-5)):
    """Compact convergence summary from a fire() trace."""
    Fu = tr['Fu']
    marks = []
    for fc in fconv_marks:
        i = np.nonzero(Fu < fc)[0]
        marks.append(int(i[0]) if len(i) else -1)
    print(f"{tag:45s} iters={tr['iters']:6d} conv={tr['converged']} E={tr['E_final']:12.4f} "
          f"|F|<{fconv_marks[0]:g}:{marks[0]:6d} <{fconv_marks[1]:g}:{marks[1]:6d} <{fconv_marks[2]:g}:{marks[2]:6d}")
    return marks
