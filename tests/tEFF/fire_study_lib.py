"""
Instrumented replica of eFF FIRE relaxation for parameter studies.

Replicates DynamicOpt::move_FIRE() + eFF_lib.cpp::run() step order exactly:
    eval() -> mass-weighted cos_vf -> velocity mixing -> dt/damping update -> LeapFrog -> esize clamp

DOF layout in pDOFs/fDOFs/vDOFs: [ apos(3*na) | epos(3*ne) | esize(ne) ]

Usage:
    import fire_study_lib as fs
    fs.load_e("H2O_spins.xyz")          # processXYZ_e path (atoms free unless '.'-prefix)
    fs.load_a("export/molecules/CH3OH.xyz")  # processXYZ path (atoms hard-fixed, electrons auto)
    tr = fs.fire(20000, dt=0.001, damping=0.1)
"""
