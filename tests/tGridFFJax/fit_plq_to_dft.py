# 2. Molecule orientation
# ════════════════════════════════════════════════════════════════════════════

def orient_molecule_flat(mol_pos):
    """PCA rotation: molecular normal → z-axis. Returns flat_pos (centered)."""
    com = mol_pos.mean(axis=0)
    centered = mol_pos - com
    cov = centered.T @ centered
    _, eigenvectors = np.linalg.eigh(cov)
    R = np.column_stack([eigenvectors[:, 2], eigenvectors[:, 1], eigenvectors[:, 0]])
    flat = centered @ R
    if flat[:, 2].mean() < 0:
        flat[:, 2] *= -1
    return flat


def find_z_top_ag(ag_pos, cell):
    cell_z = float(cell[2, 2])
    return float(ag_pos[ag_pos[:, 2] < (cell_z - 1.0), 2].max())


