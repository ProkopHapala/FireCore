def plot8_coefficients(theta, mol_syms, out_dir):
    els = sorted(set(mol_syms) & set(ELEMENTS))
    field_names = ["Pauli (A)", "London (B)", "Coulomb (C)"]
    colors      = ["#e41a1c", "#377eb8", "#4daf4a"]
    x = np.arange(len(els))
    width = 0.25

    fig, ax = plt.subplots(figsize=(8, 5))
    for j, (fname, col) in enumerate(zip(field_names, colors)):
        vals = [theta[j * N_EL + EL_MAP[el]] for el in els]
        ax.bar(x + j * width, vals, width, label=fname, color=col, alpha=0.8)

    ax.set_xticks(x + width)
    ax.set_xticklabels(els)
    ax.set_xlabel("Element")
    ax.set_ylabel("Coefficient (eV / field_unit)")
    ax.set_title("Optimal PLQ coefficients per element\n"
                 "(fitted by linear least squares to MACE E_int)")
    ax.legend(); ax.grid(True, alpha=0.2, axis="y")
    ax.axhline(0, color="k", lw=0.5)
    _save(fig, os.path.join(out_dir, "plot8_coefficients.png"))


