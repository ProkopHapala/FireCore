# 3. MACE scan — z-scan at multiple lateral positions
# ════════════════════════════════════════════════════════════════════════════

def run_mace_scan_grid(ag_syms, ag_pos, mol_syms, mol_pos_flat,
                       cell, z_vals, lat_offsets,
                       mace_model_path, device, z_top_ag):
    """Scan molecule at multiple z heights × lateral offsets using MACE.

    lat_offsets : list of (dx, dy) Å offsets added to the atop-site position.
    Returns list of dicts, each with: z_rel, e_int, mol_pos_global, mol_syms
    """
    from mace.calculators import MACECalculator  # type: ignore
    from ase import Atoms  # type: ignore

    print(f"  MACE model : {mace_model_path}")
    calc = MACECalculator(model_paths=mace_model_path,
                          device=device, default_dtype="float64")

    # Reference Ag top position (atop site)
    cell_z  = float(cell[2, 2])
    real_m  = ag_pos[:, 2] < (cell_z - 1.0)
    top_idx = np.argmax(ag_pos[real_m][:, 2])
    atop_xy = ag_pos[real_m][top_idx, :2]
    print(f"  Atop site : ({atop_xy[0]:.3f}, {atop_xy[1]:.3f}) Å")

    # E_slab (fixed Ag, computed once)
    slab_at = Atoms(symbols=ag_syms, positions=ag_pos,
                    cell=cell, pbc=[True, True, True])
    slab_at.calc = calc
    e_slab = float(slab_at.get_potential_energy())
    print(f"  E_slab = {e_slab:.4f} eV")

    # E_mol reference: same cell + pbc as E_slab/E_comb, molecule at vacuum midpoint.
    cell_z      = float(cell[2, 2])
    z_bot_img   = cell_z - 0.5
    z_mol_ref   = (z_top_ag + z_bot_img) / 2.0
    mol_ref_pos = mol_pos_flat.copy()
    mol_ref_pos[:, 0] += atop_xy[0]
    mol_ref_pos[:, 1] += atop_xy[1]
    mol_ref_pos[:, 2] += z_mol_ref
    mol_vac = Atoms(symbols=mol_syms, positions=mol_ref_pos,
                    cell=cell, pbc=[True, True, True])
    mol_vac.calc = calc
    e_mol = float(mol_vac.get_potential_energy())
    print(f"  E_mol  = {e_mol:.4f} eV  (z_ref={z_mol_ref:.2f} Å, same cell/pbc)")

    n_ag     = len(ag_syms)
    n_total  = len(z_vals) * len(lat_offsets)
    records  = []
    t0 = time.perf_counter()
    cnt = 0

    print(f"\n  Scan: {len(z_vals)} z × {len(lat_offsets)} lateral = {n_total} points")
    for dx, dy in lat_offsets:
        lat_xy = atop_xy + np.array([dx, dy])
        for z_rel in z_vals:
            mol_z = mol_pos_flat.copy()
            mol_z[:, 0] += lat_xy[0]
            mol_z[:, 1] += lat_xy[1]
            mol_z[:, 2] += z_top_ag + z_rel

            comb = Atoms(symbols=ag_syms + mol_syms,
                         positions=np.vstack([ag_pos, mol_z]),
                         cell=cell, pbc=[True, True, True])
            comb.calc = calc
            e_int = float(comb.get_potential_energy()) - e_slab - e_mol
            records.append({
                "z_rel":      z_rel,
                "e_int":      e_int,
                "mol_pos":    mol_z.copy(),
                "mol_syms":   mol_syms,
                "lat_offset": (dx, dy),
            })
            cnt += 1
            if cnt % 20 == 0 or cnt == n_total:
                print(f"    [{cnt}/{n_total}] z={z_rel:.2f}Å  "
                      f"E_int={e_int*1000:+7.1f} meV  "
                      f"{time.perf_counter()-t0:.0f}s")

    print(f"  Grid scan done in {time.perf_counter()-t0:.1f}s")
    return records, {"e_slab": e_slab, "e_mol": e_mol, "atop_xy": atop_xy}


# ════════════════════════════════════════════════════════════════════════════
# 4. PLQ field builder
# ════════════════════════════════════════════════════════════════════════════

def build_plq_fields(chgcar_path, locpot_path, out_dir):
    """Build (or load cached) PLQ B-spline coefficient grids.

    Returns
    -------
    coeffs : (nz, ny, nx, 3)  [P, L, Q] stacked
    meta   : dict with cell, origin, voxel, grid_xyz, z_ref
    """
    cache_c = os.path.join(out_dir, "_Bspline_PLQ_coeffs.npy")
    cache_m = os.path.join(out_dir, "_Bspline_PLQ_meta.npy")

    if os.path.exists(cache_c) and os.path.exists(cache_m):
        print(f"  Loading cached PLQ : {cache_c}")
        coeffs = np.load(cache_c)
        meta   = np.load(cache_m, allow_pickle=True).item()
        return coeffs, meta

    from pyBall.gridff_jax.config import DensityBackendConfig, GridConfig, FeatureToggles
    from pyBall.gridff_jax.density_backends.vasp_volumetric import VaspVolumetricBackend
    from pyBall.gridff_jax.substrate_fields import build_substrate_grids

    print(f"  CHGCAR : {chgcar_path}")
    print(f"  LOCPOT : {locpot_path}")

    backend_cfg = DensityBackendConfig(kind="vasp_volumetric",
                                       chgcar_path=chgcar_path,
                                       locpot_path=locpot_path)
    density  = VaspVolumetricBackend(backend_cfg).load()
    gc       = GridConfig(builder_mode="metal_density_plq")
    mol_elements = tuple(sorted(set(ELEMENTS)))

    print(f"  Grid shape xyz = {density.grid_shape_xyz}")
    t0 = time.perf_counter()
    grids = build_substrate_grids(density, reactive_elements=mol_elements,
                                  grid_config=gc, toggles=FeatureToggles(),
                                  prefer_jax=False)
    print(f"  B-spline built in {time.perf_counter()-t0:.1f}s")

    coeffs = np.stack([grids["pauli_coeff_zyx"],
                       grids["london_coeff_zyx"],
                       grids["coulomb_coeff_zyx"]], axis=-1)
    meta   = {"cell":     density.cell,
              "origin":   density.origin,
              "voxel":    density.voxel,
              "grid_xyz": density.grid_shape_xyz,
              "z_ref":    grids["metadata"]["z_ref"]}
    np.save(cache_c, coeffs)
    np.save(cache_m, meta)  # type: ignore[arg-type]
    print(f"  Cached → {cache_c}")
    return coeffs, meta


# ════════════════════════════════════════════════════════════════════════════
# 5. PLQ sampling
# ════════════════════════════════════════════════════════════════════════════

def sample_plq_at_positions(coeffs, meta, positions):
    """Cubic B-spline evaluation at Cartesian positions (N,3) → (N,3) [P,L,Q]."""
    from pyBall.gridff_jax.hybrid_energy.model import _sample_bspline_numpy
    from pyBall.gridff_jax.interfaces import DensityData

    density_stub = DensityData(
        cell=np.asarray(meta["cell"], dtype=float),
        origin=np.asarray(meta["origin"], dtype=float),
        voxel=meta["voxel"],
        symbols=[],
        positions=np.zeros((0, 3), dtype=float),
        charges=None,
        rho_zyx=None,
        v_loc_zyx=None,
        grid_shape_xyz_hint=meta["grid_xyz"],
    )
    result = _sample_bspline_numpy(coeffs, density_stub, positions)
    if result.ndim == 1:
        result = result[:, None]
    return result   # (N, 3)


def map_to_plq_cell(mol_pos, z_top_md, meta):
    """Shift z to align surface reference; fold x,y into PLQ cell via PBC.

    z-shift : z_top_md → meta['z_ref']
    x,y fold: fractional coordinates mod 1.0 in the 2D PLQ cell
    """
    plq_cell = np.asarray(meta["cell"], dtype=float)
    pos = mol_pos.copy().astype(float)

    # z-shift: align Ag top layer with PLQ reference height
    pos[:, 2] += float(meta["z_ref"]) - z_top_md

    # x,y fold into PLQ cell (non-orthogonal PBC)
    a1 = plq_cell[0, :2]
    a2 = plq_cell[1, :2]
    M  = np.stack([a1, a2], axis=1)        # (2,2)
    Minv = np.linalg.inv(M)
    frac = (Minv @ pos[:, :2].T).T         # fractional x,y
    frac = frac % 1.0
    pos[:, :2] = (M @ frac.T).T
    return pos


# ════════════════════════════════════════════════════════════════════════════
# 6. Linear regression
# ════════════════════════════════════════════════════════════════════════════

def build_design_matrix(records, coeffs, meta, z_top_md):
    """Build design matrix X[n, 3*N_EL] and target vector y[n].

    X[k, 0*N_EL + el] = Σ V_P(r_i)  for atoms of element el in config k
    X[k, 1*N_EL + el] = Σ V_L(r_i)
    X[k, 2*N_EL + el] = Σ V_Q(r_i)
    """
    n   = len(records)
    X   = np.zeros((n, 3 * N_EL), dtype=float)
    y   = np.zeros(n,              dtype=float)

    for k, rec in enumerate(records):
        y[k] = rec["e_int"]
        mol_pos_plq = map_to_plq_cell(rec["mol_pos"], z_top_md, meta)
        plq = sample_plq_at_positions(coeffs, meta, mol_pos_plq)  # (N_mol, 3)
        for i, sym in enumerate(rec["mol_syms"]):
            el = EL_MAP.get(sym, -1)
            if el < 0:
                continue
            X[k, 0 * N_EL + el] += plq[i, 0]   # Pauli
            X[k, 1 * N_EL + el] += plq[i, 1]   # London
            X[k, 2 * N_EL + el] += plq[i, 2]   # Coulomb

        if (k + 1) % 50 == 0 or (k + 1) == n:
            print(f"    design matrix: {k+1}/{n}")

    return X, y


def solve_plq(X, y):
    """Least-squares fit θ such that X θ ≈ y."""
    theta, residuals, rank, sv = np.linalg.lstsq(X, y, rcond=None)
    y_pred = X @ theta
    rmse   = float(np.sqrt(np.mean((y_pred - y)**2)))
    ss_res = float(np.sum((y_pred - y)**2))
    ss_tot = float(np.sum((y - y.mean())**2))
    r2     = float(1.0 - ss_res / max(ss_tot, 1e-30))
    return theta, y_pred, rmse, r2, rank


def print_theta_table(theta, mol_syms):
    """Print fitted PLQ coefficients A, B, C per element."""
    els_present = sorted(set(mol_syms) & set(ELEMENTS))
    print("\n  Fitted PLQ coefficients (eV / field_unit):")
    print(f"  {'Element':>8}  {'A (Pauli)':>14}  {'B (London)':>14}  {'C (Coulomb)':>14}")
    for el in els_present:
        i = EL_MAP[el]
        A = theta[0 * N_EL + i]
        B = theta[1 * N_EL + i]
        C = theta[2 * N_EL + i]
        print(f"  {el:>8}  {A:>14.6f}  {B:>14.6f}  {C:>14.6f}")


